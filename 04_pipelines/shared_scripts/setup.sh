#!/usr/bin/env bash
# Create venv and install dependencies (Linux / macOS).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PYTHON="${PYTHON:-python3}"
# exFAT/USB drives cannot create venv symlinks — keep venv on Linux home by default
DEFAULT_VENV="$HOME/.venvs/15_7_stroke"
VENV="${VENV:-$DEFAULT_VENV}"

echo "Project root: $ROOT"
echo "Python:       $($PYTHON --version 2>&1)"
echo "Virtualenv:   $VENV"

if [[ ! -d "$VENV" ]]; then
  mkdir -p "$(dirname "$VENV")"
  "$PYTHON" -m venv --copies "$VENV"
fi

# shellcheck source=/dev/null
source "$VENV/bin/activate"
python -m pip install --upgrade pip
pip install -r requirements.txt

# Write .env for shells / IDEs (gitignored)
_cpus="$(nproc 2>/dev/null || echo 4)"
cat > "$ROOT/.env" <<EOF
# Auto-generated by scripts/setup.sh — do not commit secrets here
export PROJECT_ROOT="$ROOT"
export PATH="$VENV/bin:\$PATH"
export OMP_NUM_THREADS="$_cpus"
export MKL_NUM_THREADS="$_cpus"
export OPENBLAS_NUM_THREADS="$_cpus"
EOF

echo ""
echo "Done. Activate with:"
echo "  source \"$VENV/bin/activate\""
echo "  source \"$ROOT/.env\""
echo ""
echo "Run ML pipeline (NY, quick test):"
echo "  python scripts/run_ml_pipeline.py --dataset ny --quick"
